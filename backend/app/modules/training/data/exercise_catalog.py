def _lines(text):
    return '\n'.join(part.strip() for part in text.split('|') if part.strip())


def ex(name, category, level, muscles, equipment, description, steps, tips, mistakes):
    return {
        'name': name,
        'category': category,
        'difficulty_level': level,
        'muscle_groups': muscles.split(),
        'equipment_needed': equipment.split(),
        'description': description,
        'instructions': _lines(steps),
        'tips': _lines(tips),
        'common_mistakes': _lines(mistakes),
    }


