def validate():
    """Catches typos in the vocabulary before they reach the database."""
    names = set()
    for item in EXERCISES:
        assert item['name'] not in names, f"duplicate: {item['name']}"
        names.add(item['name'])
        assert item['category'] in CATEGORIES, item['name']
        assert item['difficulty_level'] in LEVELS, item['name']
        assert item['muscle_groups'] and set(item['muscle_groups']) <= MUSCLES, item['name']
        assert MUSCLES == set(MUSCLE_LABELS)
        assert item['equipment_needed'] and set(item['equipment_needed']) <= EQUIPMENT, item['name']
        assert item['instructions'] and item['tips'] and item['common_mistakes'], item['name']
